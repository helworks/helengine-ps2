namespace helengine.ps2.builder;

/// <summary>
/// Writes the generated native header that tells the PS2 boot host which platform name and version to report to the
/// core. The values come from <see cref="Ps2RuntimePlatformIdentity"/>, the same constants the PS2 Play capability
/// declares, so the native runtime and the desktop player always report the same <c>PlatformInfo</c>.
/// </summary>
public sealed class Ps2RuntimePlatformInfoHeaderWriter {
    /// <summary>
    /// File name of the generated header inside the generated-core <c>runtime</c> folder.
    /// </summary>
    public const string HeaderFileName = "runtime_ps2_platform_info.hpp";

    /// <summary>
    /// Preprocessor macro that carries the platform name string literal in the generated header.
    /// </summary>
    public const string PlatformNameMacro = "HE_RUNTIME_PS2_PLATFORM_NAME";

    /// <summary>
    /// Preprocessor macro that carries the platform version string literal in the generated header.
    /// </summary>
    public const string PlatformVersionMacro = "HE_RUNTIME_PS2_PLATFORM_VERSION";

    /// <summary>
    /// Writes the platform identity header into the generated-core runtime folder, leaving an unchanged file untouched
    /// so native dependency tracking does not trigger redundant compilation.
    /// </summary>
    /// <param name="generatedCoreRootPath">Generated core root that receives the <c>runtime</c> header.</param>
    /// <returns>Absolute path of the written header.</returns>
    /// <exception cref="ArgumentException">Thrown when the generated core root path is blank.</exception>
    public string Write(string generatedCoreRootPath) {
        if (string.IsNullOrWhiteSpace(generatedCoreRootPath)) {
            throw new ArgumentException("Generated core root path must be provided.", nameof(generatedCoreRootPath));
        }

        string runtimeRootPath = Path.Combine(generatedCoreRootPath, "runtime");
        Directory.CreateDirectory(runtimeRootPath);
        string headerPath = Path.Combine(runtimeRootPath, HeaderFileName);
        string contents = BuildHeaderContents();
        if (!File.Exists(headerPath) || !string.Equals(File.ReadAllText(headerPath), contents, StringComparison.Ordinal)) {
            File.WriteAllText(headerPath, contents);
        }

        return headerPath;
    }

    /// <summary>
    /// Builds the header text: one string-literal macro for the platform name and one for the version.
    /// </summary>
    /// <returns>Complete generated header contents.</returns>
    static string BuildHeaderContents() {
        return
            "#pragma once\n\n"
            + "// Generated by the PS2 builder from Ps2RuntimePlatformIdentity; the PS2 Play capability declares the same values.\n"
            + "#define " + PlatformNameMacro + " \"" + Ps2RuntimePlatformIdentity.Name + "\"\n"
            + "#define " + PlatformVersionMacro + " \"" + Ps2RuntimePlatformIdentity.Version + "\"\n";
    }
}
